#!/usr/bin/env node
// Writes src/confusables.ts from Unicode's confusables.txt (UTS #39), kept to
// the look-alikes that can spell a reserved name: every source whose
// prototype, lower-cased, uses only the reserved names' letters.
//
//   curl -sO https://www.unicode.org/Public/18.0.0/security/confusables.txt
//   node scripts/gen-confusables.mjs confusables.txt
//
// Refuses any other file than the pinned one, so the table only changes with a
// deliberate bump of VERSION and SHA256 here.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const VERSION = "18.0.0";
const SHA256 = "6ed3ee967c9dfdf6677d563c9985182fbc50a2efb7d6059cd57b2e2ce18f5b92";
// The reserved names in src/display-name.ts; the test fails when they need a letter this lacks.
const ALPHABET = [...new Set("orangecheck ochk ochk.io ochk.app".replace(/ /g, ""))].sort().join("");
// Our one addition: Cyrillic ka and Greek kappa map to kra, which most faces draw as a small k.
const KRA = String.fromCodePoint(0x138);

const path = process.argv[2];
if (!path) throw new Error("usage: gen-confusables.mjs <confusables.txt>");
const raw = readFileSync(path);
const sha = createHash("sha256").update(raw).digest("hex");
if (sha !== SHA256) throw new Error(`confusables.txt is ${sha}, not the pinned ${VERSION} (${SHA256})`);
let text = raw.toString("utf8");
if (text.charCodeAt(0) === 0xfeff) text = text.slice(1);
if (!text.includes(`# Version: ${VERSION}`)) throw new Error(`confusables.txt is not version ${VERSION}`);

const cp = (hex) => String.fromCodePoint(parseInt(hex, 16));
const table = new Map();
for (const line of text.split("\n")) {
  const data = line.split("#")[0].trim();
  if (!data) continue;
  const [source, target] = data.split(";").map((f) => f.trim());
  table.set(cp(source), target.split(" ").filter(Boolean).map(cp).join(""));
}

// A prototype is never itself a source, so one pass is the whole skeleton.
for (const ch of ALPHABET + KRA) if (table.has(ch)) throw new Error(`${ch} is a source in ${VERSION}`);
for (const target of table.values()) {
  for (const ch of target) if (table.has(ch)) throw new Error(`prototype ${target} maps further in ${VERSION}`);
}

const byPrototype = new Map();
const add = (source, prototype) => byPrototype.set(prototype, (byPrototype.get(prototype) ?? "") + source);
for (const [source, target] of table) {
  const prototype = target.toLowerCase().replaceAll(KRA, "k");
  if ([...prototype].every((ch) => ALPHABET.includes(ch))) add(source, prototype);
}
add(KRA, "k");

const BACKSLASH = String.fromCharCode(92);
const esc = (s) => [...s].map((ch) => `${BACKSLASH}u{${ch.codePointAt(0).toString(16)}}`).join("");
const lines = [...byPrototype]
  .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
  .map(([prototype, sources]) => `  [${JSON.stringify(prototype)}, "${esc(sources)}"],`);
const count = [...byPrototype.values()].reduce((n, s) => n + [...s].length, 0);

const out = [
  `// Generated by scripts/gen-confusables.mjs from Unicode confusables.txt ${VERSION}`,
  `// (sha256 ${SHA256}). Do not edit.`,
  `// Unicode data: copyright Unicode, Inc., under the Unicode License v3, https://www.unicode.org/license.txt`,
  ``,
  `/** The letters of the reserved names: the only prototypes kept. */`,
  `export const CONFUSABLE_ALPHABET = ${JSON.stringify(ALPHABET)};`,
  ``,
  `/**`,
  ` * UTS #39 prototypes, lower-cased, each with the characters drawn like it that`,
  ` * can spell a reserved name (${count} in all). Kra counts as k.`,
  ` */`,
  `export const CONFUSABLE_PROTOTYPES: ReadonlyArray<readonly [string, string]> = [`,
  ...lines,
  `];`,
  ``,
];
writeFileSync(new URL("../src/confusables.ts", import.meta.url), out.join("\n"));
console.log(`wrote src/confusables.ts: ${count} characters, ${byPrototype.size} prototypes`);
