#!/usr/bin/env node
/*
 * Every picture of the person the package draws, from one photograph:
 *
 *   node scripts/portrait/build.mjs [source] [--seed N]   write the files
 *   node scripts/portrait/build.mjs --check                fail if a file differs from a fresh run
 *
 * The source (scripts/portrait/source.webp by default) is square, head and
 * shoulders, with the person's matte as its alpha. scripts/portrait/portrait.json
 * holds the seed, the tone settings and the named places on the face. SOURCE.md
 * says where the photograph came from and under what licence. It writes:
 *
 * - src/motion/portrait-points.data.ts: a blue-noise stipple of the photograph,
 *   ParticlePortrait's default (bustPoints). Dots gather where the picture is dark
 *   on paper and where it is lit on a dark ground, so it is a positive on both;
 *   each dot is stored once with the grounds that draw it, and keeps its ink.
 * - src/motion/portrait-poster.ts: the settled frame, sparser, as two SVG paths of
 *   squares (ink on paper, light on a dark ground), the still before the canvas
 *   draws, without script and under reduced motion; and the named places.
 * - src/brand/portrait-tone.ts: the ink on a 128 grid, which HalftoneCanvas screens.
 * - src/motion/deck-points.data.ts: that ink on a 45° screen (deckPortraitPoints).
 * - art/portrait-halftone-{600,1200}.webp: HalftoneSphere's dot layer, black dots
 *   on transparent, masked to the ball.
 *
 * Same source and seed, same files: every step is integer or IEEE arithmetic in a
 * fixed order (scripts/portrait/lib.mjs), the source decodes bit-exactly (WebP's
 * lossy decode is specified to the bit), and the layers' alpha is lossless.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

import { deckScreen, inkTone, lightGrid, pack, planes, poster, sphereLayer, stipple } from './lib.mjs';

const pkg = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const require = createRequire(join(pkg, 'package.json'));
const sharp = require('sharp');

const args = process.argv.slice(2);
const CHECK = args.includes('--check');
const seedAt = args.indexOf('--seed');
const SOURCE = args.find((a, i) => !a.startsWith('--') && (seedAt < 0 || i !== seedAt + 1)) ?? join(pkg, 'scripts/portrait/source.webp');
const config = JSON.parse(readFileSync(join(pkg, 'scripts/portrait/portrait.json'), 'utf8'));
const SEED = seedAt >= 0 ? Number(args[seedAt + 1]) : config.seed;
if (!Number.isInteger(SEED) || SEED < 0) throw new Error(`portrait: the seed must be a whole number, not ${args[seedAt + 1]}`);

const GRID = 360; // the light is sampled on this grid by the stipple
const TONE = 128; // HalftoneCanvas's ink grid
const DECK_ACROSS = 104;
const SPHERE_ACROSS = 110; // the ball's dots across, at either size
const ORIGIN = relative(pkg, SOURCE);

const { data, info } = await sharp(SOURCE).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
if (info.width !== info.height || info.channels !== 4) throw new Error(`portrait: ${ORIGIN} must be square with alpha (${info.width}×${info.height}, ${info.channels} channels)`);
const W = info.width;
const p = planes(data, W);

const light = lightGrid(p, W, GRID, config.light);
const st = stipple(light, GRID, { seed: SEED, sequence: config.sequence, dots: config.dots, tries: 12, fade: config.fade, curve: config.curve, rim: config.rim });
const grounds = Uint8Array.from(st.dots, (d) => d[3]);
const count = (g) => st.dots.filter((d) => d[3] & g).length;
const b64 = (bytes) => Buffer.from(bytes).toString('base64');
const head = `// Generated by scripts/portrait/build.mjs from ${ORIGIN}, seed ${SEED}. Do not edit: run the script.\n\n`;

const files = new Map();
files.set(
    'src/motion/portrait-points.data.ts',
    head +
        `/** The portrait as a blue-noise stipple: ${count(1)} dots on paper, ${count(2)} on a dark ground, ${st.dots.length} in all. Uint16 x, y pairs (little-endian, 0..65535 across the square), then a Uint8 ink each. */\n` +
        // The packed bytes carry ink (0 lit, 1 dark), as every point set's tone does.
        `export const PORTRAIT_POINTS_B64 =\n    '${b64(pack(st.dots.map(([x, y, l]) => [x, y, 1 - l])))}';\n\n` +
        `/** Per dot, the grounds that draw it: 1 paper, 2 a dark ground, 3 both. */\n` +
        `export const PORTRAIT_GROUNDS_B64 =\n    '${b64(grounds)}';\n\n` +
        `/** The stipple's spacing at full density, as a fraction of the square. */\n` +
        `export const PORTRAIT_PITCH = ${+st.pitch.toFixed(6)};\n`
);

const anchors = Object.entries(config.anchors);
for (const [k, [u, v]] of anchors) if (!(u >= 0 && u <= 1 && v >= 0 && v <= 1)) throw new Error(`portrait: anchor ${k} is outside the square`);
files.set(
    'src/motion/portrait-poster.ts',
    head +
        `/** The portrait's settled frame, sparser, ink on paper: one path of squares in a 0 0 1000 1000 box. */\n` +
        `export const PORTRAIT_POSTER = '${poster(st, false, config.poster)}';\n\n` +
        `/** The same frame on a dark ground, where the dots gather where the face is lit. */\n` +
        `export const PORTRAIT_POSTER_DARK = '${poster(st, true, config.poster)}';\n\n` +
        `/** Named places on the portrait, in its unit square, for callouts: where a label's + lands. */\n` +
        `export const PORTRAIT_ANCHORS = {\n` +
        anchors.map(([k, v]) => `    ${k}: [${v.map((n) => +n.toFixed(3)).join(', ')}],\n`).join('') +
        `} as const satisfies Record<string, readonly [number, number]>;\n`
);

// The ink for the halftones: the same light, on HalftoneCanvas's grid.
const tone = inkTone(light, GRID, TONE);
files.set(
    'src/brand/portrait-tone.ts',
    `/*\n * The portrait as ink, ${TONE} × ${TONE}, one byte per cell (0 = paper, 255 = full\n * ink), 0 off the figure. Generated by scripts/portrait/build.mjs from\n * ${ORIGIN}, the photograph ParticlePortrait's dots come from; HalftoneCanvas\n * screens it live. Do not edit: run the script.\n */\n` +
        `export const PORTRAIT_TONE_SIZE = ${TONE};\nexport const PORTRAIT_TONE_B64 =\n    '${b64(tone)}';\n`
);

const deck = deckScreen(tone, TONE, DECK_ACROSS);
files.set(
    'src/motion/deck-points.data.ts',
    `// Generated from brand/portrait-tone.ts by scripts/portrait/build.mjs. Do not edit: run the script.\n\n` +
        `/** The portrait's ink as ${deck.length} dots on a 45° screen ${DECK_ACROSS} dots across: Uint16 x, y pairs (little-endian, 0..65535 across the square), then a Uint8 ink each. */\n` +
        `export const DECK_POINTS_B64 =\n    '${b64(pack(deck))}';\n\n` +
        `/** The screen's pitch, as a fraction of the square. */\n` +
        `export const DECK_PITCH = ${+(1 / DECK_ACROSS).toFixed(6)};\n`
);

// The ball's dot layer: ink-coloured pixels, the dots in the alpha, which WebP keeps losslessly at alphaQuality 100.
const INK = [12, 10, 9];
const layers = new Map();
for (const px of [600, 1200]) {
    const alpha = sphereLayer(tone, TONE, px, SPHERE_ACROSS);
    const rgba = new Uint8Array(px * px * 4);
    for (let i = 0; i < px * px; i++) rgba.set([...INK, alpha[i]], i * 4);
    layers.set(`art/portrait-halftone-${px}.webp`, alpha);
    files.set(
        `art/portrait-halftone-${px}.webp`,
        await sharp(rgba, { raw: { width: px, height: px, channels: 4 } })
            .webp({ quality: 90, alphaQuality: 100, effort: 6 })
            .toBuffer()
    );
}

if (CHECK) {
    let bad = 0;
    const fail = (msg) => (console.error(`✗ portrait: ${msg}; run node scripts/portrait/build.mjs`), bad++);
    for (const [f, want] of files) {
        let have;
        try {
            have = readFileSync(join(pkg, f));
        } catch {
            fail(`${f} is missing`);
            continue;
        }
        if (!f.endsWith('.webp')) {
            if (have.toString('utf8') !== want) fail(`${f} differs from a fresh run`);
            continue;
        }
        // An encoder may write other bytes for the same picture; the picture is what must match: the alpha
        // exactly, and the ink wherever a dot is.
        const { data: got, info: gi } = await sharp(have).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
        const alpha = layers.get(f);
        const px = Math.sqrt(alpha.length);
        if (gi.width !== px || gi.height !== px) {
            fail(`${f} is ${gi.width}×${gi.height}, not ${px}×${px}`);
            continue;
        }
        let off = 0;
        let tint = 0;
        for (let i = 0; i < px * px; i++) {
            if (got[i * 4 + 3] !== alpha[i]) off++;
            else if (alpha[i] && INK.some((c, k) => Math.abs(got[i * 4 + k] - c) > 3)) tint++;
        }
        if (off || tint) fail(`${f}: ${off} pixels' alpha and ${tint} pixels' ink differ from a fresh run`);
    }
    if (bad) process.exit(1);
    console.log(`✓ portrait: ${files.size} files match a fresh run from ${ORIGIN}, seed ${SEED}`);
} else {
    for (const [f, body] of files) writeFileSync(join(pkg, f), body);
    const kb = (f) => `${(Buffer.byteLength(files.get(f)) / 1024).toFixed(1)} KB`;
    console.log(
        `✓ portrait from ${ORIGIN}, seed ${SEED}: ${count(1)} dots on paper, ${count(2)} on dark, ${st.dots.length} stored; ` +
            `deck ${deck.length} dots; ${[...files.keys()].map((f) => `${f.split('/').pop()} ${kb(f)}`).join(', ')}`
    );
}
